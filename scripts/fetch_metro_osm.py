"""Fetch Kolkata Metro stations and line membership from OpenStreetMap (Overpass API).

Outputs: /app/frontend/src/data/metro_stations.json
  [{ name, lines: ["Blue Line", ...], lat, lon, osmId }]

Data © OpenStreetMap contributors, ODbL 1.0 — same licence as the pandal source.
Repeatable: re-run to refresh. Name variants are normalised so the same station
is never split (e.g. "Esplanade (Line 1)" / "Esplanade (Line 2)", "Satyajit Ray"
/ "Satyajit Roy", "Sakher bazar" / "Sakher Bazar").
"""
import json
import re
import time
from pathlib import Path

import requests

OVERPASS = "https://overpass-api.de/api/interpreter"
HEADERS = {"User-Agent": "PujoPath/1.0 (data import; ODbL attribution)"}
BBOX = "22.30,88.10,22.85,88.75"
ROOT = Path("/app")
OUT = ROOT / "frontend/src/data/metro_stations.json"


def norm(name: str) -> str:
    s = name.lower()
    s = re.sub(r"\s*\((?:line \d|blue line|green line|orange line|yellow line)\)\s*", " ", s)
    s = s.replace("metro station", "")
    s = s.replace("satyajit roy", "satyajit ray")
    s = s.replace("dakshineshwar", "dakshineswar")
    s = re.sub(r"\s+", " ", s).strip()
    return s


DISPLAY_FIX = {"Satyajit Ray": "Satyajit Ray", "Dakshineswar": "Dakshineswar"}


def overpass(q: str, retries: int = 3) -> dict:
    for attempt in range(retries):
        try:
            r = requests.post(OVERPASS, data={"data": q}, timeout=180, headers=HEADERS)
            if r.status_code == 200:
                return r.json()
            print(f"  overpass {r.status_code}, retry {attempt + 1}")
        except Exception as exc:  # noqa: BLE001
            print(f"  overpass error {exc}, retry {attempt + 1}")
        time.sleep(5)
    raise RuntimeError("Overpass unavailable")


def main() -> None:
    # 1. all subway stations in the metro area
    q = (
        "[out:json][timeout:90];"
        f'(node["station"="subway"]({BBOX});node["railway"="station"]["subway"="yes"]({BBOX}););out body;'
    )
    stations = overpass(q)["elements"]

    # 2. subway route relations (members are ordered along the line)
    rels = overpass(f'[out:json][timeout:90];relation["route"="subway"]({BBOX});out body;')["elements"]

    # 3. resolve member node names in chunks
    node_ids = sorted(
        {m["ref"] for rel in rels for m in rel.get("members", []) if m["type"] == "node"}
    )
    node_names = {}

    def chunked(seq, size):
        for i in range(0, len(seq), size):
            yield seq[i : i + size]

    for chunk in chunked(node_ids, 200):
        ids = ",".join(str(i) for i in chunk)
        for e in overpass(f"[out:json][timeout:90];node(id:{ids});out body;")["elements"]:
            name = e.get("tags", {}).get("name")
            if name:
                node_names[e["id"]] = name

    # canonical line name (strip direction suffix) -> ordered member station names
    lines = {}
    for rel in rels:
        tags = rel.get("tags", {})
        raw = tags.get("name", "")
        if not raw:
            continue
        canonical = re.sub(r"\s*\([^)]*→[^)]*\)\s*", " ", raw).strip()
        ordered = [
            node_names[m["ref"]]
            for m in rel.get("members", [])
            if m["type"] == "node" and m.get("ref") in node_names
        ]
        if canonical not in lines or len(ordered) > len(lines[canonical]):
            lines[canonical] = ordered

    for name, ordered in sorted(lines.items()):
        print(f"{name}: {ordered}")

    # 4. merge stations by normalised name; union their lines; average duplicate pins
    merged = {}
    for e in stations:
        tags = e.get("tags", {})
        raw = tags.get("name")
        if not raw:
            continue
        key = norm(raw)
        rec = merged.setdefault(
            key,
            {"name": raw, "lines": [], "lat": e["lat"], "lon": e["lon"], "osmId": f"node/{e['id']}"},
        )
        rec["_lats"] = rec.get("_lats", [rec["lat"]]) + [e["lat"]]
        rec["_lons"] = rec.get("_lons", [rec["lon"]]) + [e["lon"]]
        rec["lat"] = sum(rec["_lats"]) / len(rec["_lats"])
        rec["lon"] = sum(rec["_lons"]) / len(rec["_lons"])

    for line_name, ordered in lines.items():
        for member in ordered:
            key = norm(member)
            if key in merged and line_name not in merged[key]["lines"]:
                merged[key]["lines"].append(line_name)

    out = [s for s in merged.values() if s["lines"]]  # drop stations with no line (unreferenced stops)
    out.sort(key=lambda s: s["name"])
    for s in out:
        s.pop("_lats", None)
        s.pop("_lons", None)

    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(out, fh, ensure_ascii=False, indent=1)

    # typed TS module (tsconfig has no resolveJsonModule; the bundle imports this)
    ts = (
        "// Generated by scripts/fetch_metro_osm.py — data © OpenStreetMap contributors, ODbL 1.0.\n"
        "// Do not edit by hand; re-run the script to refresh.\n"
        'import type { MetroStation } from "@/lib/types";\n\n'
        "export const METRO_STATIONS: MetroStation[] = "
        + json.dumps(out, ensure_ascii=False, indent=1)
        + ";\n"
    )
    (ROOT / "frontend/src/data/metro_stations.data.ts").write_text(ts, encoding="utf-8")
    print(f"\nwrote {len(out)} stations -> {OUT}")


if __name__ == "__main__":
    main()
